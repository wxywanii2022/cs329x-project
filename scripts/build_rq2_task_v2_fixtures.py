"""Write v0.2 regression fixtures for the learner view v2 (goal only, no table name).

Pilot 1 showed the frozen assessor scoring B2 as 2 when the learner repeated the
assignment's table ID and N/A when it did not, so B2 was never 0. Learner view v2
(tasks.public_task) shows only the goal. These hand-labeled decision points check
that the same assessor and the evaluator now use the full 0/1/2 range on that
format. They are constructed cases, not evidence of accuracy. data/rq2/v02_fixtures
is left unchanged because the RQ1 v3 preregistration pins its hashes.

python3 scripts/build_rq2_task_v2_fixtures.py
"""
import csv
import json
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "data" / "rq2" / "task_v2_fixtures"
GOAL = ('Task assignment: {"instructions":"You need to tell a colleague how completed service requests changed '
        'from September to October. Work with the task assistant to prepare the summary."}')

# (item_id, behavior, expected v0.2 label, why, judged learner request)
CASES = [
    ("T01", "B1", "0", "Judgeable request, no output properties, none supplied by the task",
     "Can you help me summarize how completed service requests changed?"),
    ("T02", "B2", "0", "Evidence-dependent request with no support requirement; the task supplies no source",
     "Can you help me summarize how completed service requests changed?"),
    ("T03", "B2", "1", "Broad accuracy instruction without a usable support standard",
     "Summarize how completed service requests changed, and make sure the numbers are accurate."),
    ("T04", "B2", "2", "Requested calculation and a source for each figure",
     "Summarize how completed service requests changed. Show the calculation and say which table each number comes from."),
    ("T05", "B2", "2", "Task-relevant source type required for the figures",
     "Summarize how completed service requests changed, using the official monthly operations counts for both months."),
]


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    lines, rows = [], []
    for item_id, behavior, label, reason, request in CASES:
        messages = [{"turn_id": "1", "role": "evidence", "content": GOAL},
                    {"turn_id": "2", "role": "user", "content": request}]
        lines.append(json.dumps({"item_id": item_id, "session_id": "task-v2-fixture-" + item_id, "agent": "scripted",
                                 "behavior": behavior, "target_turn_id": "2", "visible_instructions": "",
                                 "messages": messages}, ensure_ascii=False))
        rows.append({"item_id": item_id, "behavior": behavior, "label": label, "reason": reason})
    (OUT / "items.jsonl").write_text("\n".join(lines) + "\n", encoding="utf-8")
    with (OUT / "reference.csv").open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["item_id", "behavior", "label", "reason"])
        writer.writeheader()
        writer.writerows(rows)
    (OUT / "README.md").write_text(
        "# v0.2 fixtures for the RQ2 learner view v2\n\n"
        "Five hand-built B1/B2 request decision points in which the assignment shows only the goal "
        "(no table name). Generated by `scripts/build_rq2_task_v2_fixtures.py`; edit the script, not these "
        "files. Constructed cases, not a sample: they check the label range, not accuracy. The original "
        "13 fixtures stay in `data/rq2/v02_fixtures` (pinned by the RQ1 v3 preregistration).\n",
        encoding="utf-8")
    print(f"{len(rows)} fixtures -> {OUT}")


if __name__ == "__main__":
    main()
